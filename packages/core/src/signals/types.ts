// Signals domain - the signal DEFINITION: a signal's durable identity and curation, in the
// `signals` table, independent of its history in `signal_points`. A signal can exist before its
// first data point and keeps its curation when its source goes away.
//
// A definition's `id` IS the signal id - one shared namespace with `signal_points.signal_id`,
// `goals.signal_id`, trigger filters on `fields.signal_id` and the SPA pickers. Dotted ids
// ('github.stars.acme') are a convention of derived signals, not a syntax; curated signals take
// plain slugs ('mrr').

/**
 * Where a signal's identity comes from. `derived` = auto-registered by the derive machinery (its
 * id is generated by deriver code, so renaming it is refused - the next pull would re-create the
 * old id); `manual` = human-created, points arrive by hand entry, a provider sync or a formula.
 */
export type SignalSource = 'derived' | 'manual'
export const SIGNAL_SOURCES: SignalSource[] = ['derived', 'manual']

// interval / accumulation / direction are the slice of this vocabulary a PROVIDER's measure
// catalogue declares defaults in, so they live in @silkweave/box-provider-kit - the package a provider is
// allowed to depend on. Re-exported here so this file stays the one import site for the signal
// vocabulary.
export {
  SIGNAL_ACCUMULATIONS,
  SIGNAL_DIRECTIONS,
  SIGNAL_INTERVALS,
  type SignalAccumulation,
  type SignalDirection,
  type SignalInterval,
} from '@silkweave/box-provider-kit'

import type { SignalAccumulation, SignalDirection, SignalInterval } from '@silkweave/box-provider-kit'

/**
 * Who wrote a `signal_points` row:
 *   • `live`     - machine-materialized and re-derivable: channel derivers, provider syncs,
 *                  increment buckets aggregated from events. Each writer replaces its own.
 *   • `backfill` - machine-reconstructed history (download curves, star history). Written once,
 *                  never replaced by a derive.
 *   • `manual`   - human-entered, durable, never machine-deleted.
 * `source` is part of the PK, so no class can overwrite another; reads pick one per bucket with
 * live > backfill > manual precedence (signals/points.ts mergeSignalPoints).
 */
export type SignalPointSource = 'manual' | 'live' | 'backfill'
export const SIGNAL_POINT_SOURCES: SignalPointSource[] = ['manual', 'live', 'backfill']

/**
 * The default channel for source-less (manual) signals. `channel` is required on every definition
 * (it is the dashboard section key AND, for derived signals, the derive-machinery join), so
 * signals with no external source need a channel of their own - one with no deriver behind it.
 */
export const MANUAL_SIGNAL_CHANNEL = 'business'

export interface SignalDefinition {
  /** The signal id - one namespace with `signals.signal_id` (see the header comment). */
  id: string
  /** Display name. For derived signals this is the curated override of the deriver's denormalized
   *  row label - read paths prefer it, and auto-registration never overwrites it. */
  label: string
  /** The dashboard section within the channel ("Finance", "Audience", "North Star"). */
  signal_group: string
  /** Display unit ('dl', 'posts', '$'), or null for a bare count. */
  unit: string | null
  /** Dashboard section key + (for derived signals) the derive channel that owns the rows.
   *  Source-less signals default to `business` - just a channel with no deriver. */
  channel: string
  source: SignalSource
  interval: SignalInterval
  accumulation: SignalAccumulation
  direction: SignalDirection
  /** Owning users.id. The FIRST step of ownership resolution; null falls back to the signal-owner
   *  settings (channel default → account binding → unowned; signals/owners.ts). */
  owner: string | null
  /** Free text: what this number means, how it is gathered, what to watch for - exactly the
   *  context an agent (or a new teammate) needs, stored where both already read. */
  description: string
  /**
   * Signal ids this one is DRIVEN BY - edges point down at the drivers
   * (`mrr.depends_on = ['churn-rate', 'new-customers']`). A curated causal claim and nothing
   * more: edges never do arithmetic; a parent's value always comes from its own data. Kept
   * acyclic and known-ids-only on write, mirroring `initiatives.blocked_by`.
   */
  depends_on: string[]
  /**
   * The provider binding (Track C): the `data_sources.id` whose sync owns this signal's live
   * points, and the provider-native measure key it subscribes to. Both or neither - CONNECTEDNESS
   * IS `data_source_id != null`, which is why `source` above stays derived|manual. A connected
   * signal is a MANUAL signal (human-named, renameable, hand-correctable) that happens to have a
   * live feed; a `derived` one may never carry a binding, since a deriver already owns its rows.
   */
  data_source_id: string | null
  measure_key: string | null
  /**
   * The formula this signal's points are COMPUTED from (signals/formula.ts), e.g.
   * `churned-mrr / start(mrr) * 100`, or null for an ordinary signal. A formula signal IS
   * `formula != null` - `source` stays `manual` (it never grows a third value) and it may carry no
   * provider binding. Its `depends_on` is derived from the formula's refs on write; its points are
   * computed on read, and a manual point on it overrides the computed value of that bucket.
   */
  formula: string | null
  /** Levels worth a `signal.threshold` event when the signal reaches or crosses them upward,
   *  ascending. Empty for none. */
  thresholds: number[]
  /** Manual ordering within lists (lower first), like every other `sort` here. */
  sort: number
  created_at: string
  updated_at: string
  /** users.id that created / last edited the row; null for machine writes (auto-registration). */
  created_by: string | null
  updated_by: string | null
}

/** Partial upsert input - `id` identifies the row; any provided field overwrites, the rest persist. */
export interface SignalDefinitionInput {
  id: string
  label?: string
  signal_group?: string
  unit?: string | null
  channel?: string
  source?: SignalSource
  interval?: SignalInterval
  accumulation?: SignalAccumulation
  direction?: SignalDirection
  owner?: string | null
  description?: string
  depends_on?: string[]
  /** Set both to bind, pass null for both to unbind (the points stay - they are real
   *  observations; they simply stop refreshing). One without the other is refused. */
  data_source_id?: string | null
  measure_key?: string | null
  /** Set to make this a formula signal (depends_on then follows the formula's refs); null clears
   *  the formula (depends_on is kept as it is). */
  formula?: string | null
  /** Replaces the list; finite numbers, stored ascending and de-duplicated. */
  thresholds?: number[]
  sort?: number
  /** users.id performing this mutation (stamps created_by on insert, updated_by always). */
  actor?: string
}
